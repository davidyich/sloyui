export function catalogueText(text:string,locale:'ru'|'en'):string {
 if(locale==='ru')return text;
 const trimmed=text.trim(),exact=catalogueDictionary[trimmed];
 if(exact)return text.slice(0,text.indexOf(trimmed))+exact+text.slice(text.indexOf(trimmed)+trimmed.length);
 const templates:[RegExp,(match:RegExpMatchArray)=>string][]=[
  [/^Настройка (.+); допустимые значения указаны в типе\.$/,m=>m[1]+' setting; valid values are specified by the type.'],
  [/^Начальное значение (.+)\.$/,m=>'Initial '+m[1]+' value.'],
  [/^Обработчик события (.+)\.$/,m=>m[1]+' event handler.'],
  [/^Управляет отображением (.+)\.$/,m=>'Controls '+m[1]+' visibility.'],
  [/^Слот отображения (.+)\.$/,m=>m[1]+' rendering slot.'],
 ];
 for(const [pattern,render]of templates){const match=trimmed.match(pattern);if(match)return render(match);}
 return text;
}
export function useCatalogText(){ const locale=useLocale(); return useCallback((text:string)=>catalogueText(text,locale),[locale]); }

/** Localizes only explicit, immutable catalogue fixture objects at their call sites. */
export function localizeCatalogueFixture<T>(fixture:T,translate:(text:string)=>string):T {
 const keys=new Set(['label','title','description','body','header','name','text','createdAt','emptyLabel','placeholder','aria-label','content','children','keywords','aliases','group','meta','detail','disabledReason','emptyTitle','emptyDescription','caption']);
 const walk=(value:unknown,key?:string):unknown=>{
  if(typeof value==='string')return !key||keys.has(key)?translate(value):value;
  if(Array.isArray(value))return value.map(item=>walk(item,key));
  if(!value||typeof value!=='object')return value;
  // React fixture previews have the same immutable shape; no DOM or consumer state is touched.
  const record=value as Record<string,unknown>;
  if('$$typeof' in record&&'props' in record)return {...record,props:walk(record.props)};
  return Object.fromEntries(Object.entries(record).map(([name,item])=>[name,walk(item,name)]));
 };
 return walk(fixture) as T;
}

